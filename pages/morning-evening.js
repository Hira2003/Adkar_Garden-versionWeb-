// ---------- State ----------
let currentTab = 'morning'; // 'morning' | 'evening'
let today = new Date().toISOString().split('T')[0];
let progress = { morning: [], evening: [] }; // arrays of current counts per index

const STORAGE_KEY = 'adkar_sabah_masaa_progress';

// ---------- DOM ----------
const tabMorningBtn = document.getElementById('tabMorningBtn');
const tabEveningBtn = document.getElementById('tabEveningBtn');
const dhikrListContainer = document.getElementById('dhikrListContainer');
const progressSummary = document.getElementById('progressSummary');

// ---------- Storage ----------
function loadProgress() {
  const saved = localStorage.getItem(STORAGE_KEY);
  const now = new Date().toISOString().split('T')[0];

  let data = null;
  if (saved) {
    try {
      data = JSON.parse(saved);
    } catch (e) {
      data = null;
    }
  }

  if (!data || data.date !== now) {
    // New day: reset
    progress = {
      morning: morningAdkar.map(() => 0),
      evening: eveningAdkar.map(() => 0)
    };
    today = now;
    saveProgress();
  } else {
    progress = data.progress;
    today = data.date;
    // Guard against list length changes
    if (progress.morning.length !== morningAdkar.length) {
      progress.morning = morningAdkar.map((_, i) => progress.morning[i] || 0);
    }
    if (progress.evening.length !== eveningAdkar.length) {
      progress.evening = eveningAdkar.map((_, i) => progress.evening[i] || 0);
    }
  }
}

function saveProgress() {
  localStorage.setItem(STORAGE_KEY, JSON.stringify({ date: today, progress }));
}

// ---------- Rendering ----------
function getCurrentList() {
  return currentTab === 'morning' ? morningAdkar : eveningAdkar;
}

function render() {
  const list = getCurrentList();
  const counts = progress[currentTab];

  dhikrListContainer.innerHTML = '';
  let doneCount = 0;

  list.forEach((item, index) => {
    const count = counts[index] || 0;
    const isDone = count >= item.target;
    if (isDone) doneCount++;

    const card = document.createElement('div');
    card.className = 'dhikr-card' + (isDone ? ' done' : '');

    const textEl = document.createElement('div');
    textEl.className = 'dhikr-card-text';
    textEl.innerText = item.text;

    const footer = document.createElement('div');
    footer.className = 'dhikr-card-footer';

    const pill = document.createElement('div');
    pill.className = 'dhikr-count-pill';
    pill.innerText = isDone ? '✓ تم' : `${count} / ${item.target}`;

    const barWrap = document.createElement('div');
    barWrap.className = 'dhikr-progress-bar';
    const fill = document.createElement('div');
    fill.className = 'dhikr-progress-fill';
    fill.style.width = Math.min(100, (count / item.target) * 100) + '%';
    barWrap.appendChild(fill);

    footer.appendChild(pill);
    footer.appendChild(barWrap);

    card.appendChild(textEl);
    card.appendChild(footer);

    card.addEventListener('click', () => {
      if (counts[index] < item.target) {
        counts[index]++;
      } else {
        // Allow resetting an already-completed dhikr by tapping again
        counts[index] = 0;
      }
      saveProgress();
      render();
    });

    dhikrListContainer.appendChild(card);
  });

  progressSummary.innerText = `تم إكمال ${doneCount} من ${list.length}`;
}

function setTab(tab) {
  currentTab = tab;
  tabMorningBtn.classList.toggle('active', tab === 'morning');
  tabEveningBtn.classList.toggle('active', tab === 'evening');
  render();
}

// ---------- Events ----------
tabMorningBtn.addEventListener('click', () => setTab('morning'));
tabEveningBtn.addEventListener('click', () => setTab('evening'));

// ---------- Init ----------
loadProgress();
setTab('morning');
